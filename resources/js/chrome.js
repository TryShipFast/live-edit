/**
 * Mount the overlay and return every element the editor drives.
 */
export function createChrome() {
    // Page-level affordances live in the document; the UI lives in the shadow.
    const pageStyle = document.createElement('style');
    pageStyle.id = 'live-edit-page-css';
    pageStyle.textContent = PAGE_CSS;
    document.head.append(pageStyle);

    const root = document.createElement('div');
    root.id = 'live-edit-ui';
    document.body.append(root);
    const shadow = root.attachShadow({ mode: 'open' });
    const style = document.createElement('style');
    style.textContent = CHROME_CSS;
    shadow.append(style);

    const config = window.liveEditToolbar ?? {};

    // ---- toolbar -----------------------------------------------------------
    const toolbar = el('div', 'le-toolbar');

    /* The mark, so the bar is plainly ours and not something the theme grew.
       A white disc on carbon: one shape, no colour, which is the whole idea
       of this bar. */
    /*
     * A link when there is somewhere to go, a plain mark when there is not.
     *
     * The dashboard is where a licence is renewed and colleagues are added or
     * removed, and until now the only route to it was remembering the
     * address. The mark is the one thing on this bar that is plainly ours and
     * was doing nothing, which is exactly what a way home should be.
     *
     * A site that has not registered has no page to open, so it keeps the
     * mark and gets no dead link.
     */
    const consoleUrl = window.liveEditEditor?.console ?? null;
    const mark = el(consoleUrl ? 'a' : 'span', 'le-mark');
    mark.innerHTML = '<svg width="16" height="16" viewBox="0 0 32 32" aria-hidden="true">'
        + '<rect x="3" y="3" width="20" height="20" rx="3" fill="none" stroke="#0B0C0F" stroke-width="2.5"/>'
        + '<path d="M16 15 L16 30 L19.6 26.4 L22.2 31.2 L24.6 30 L22 25.3 L27 25.3 Z" fill="#3148F5" stroke="#fff" stroke-width="1.4" stroke-linejoin="round"/></svg>';

    if (consoleUrl) {
        mark.href = consoleUrl;
        // A new tab, because the client is in the middle of editing a page and
        // sending them away would lose whatever they had open.
        mark.target = '_blank';
        mark.rel = 'noopener';
        mark.title = 'Your dashboard: licence, editors, settings';
        mark.setAttribute('aria-label', 'Open your dashboard');
    }

    /* Empty until editing starts.

       It used to read "Viewing as visitor", which said the same thing as the
       button beside it: a bar offering "Edit site" is plainly not editing
       anything. Two ways of saying one state, in the smallest piece of
       furniture in the product. What replaces it is not silence for its own
       sake — the text that appears while editing tells somebody what to click,
       which is worth the room. */
    const status = el('span', 'le-status le-when-roomy');
    const dot = el('span', 'le-dot');
    const statusText = el('span', null, '');
    status.append(dot, statusText);
    toolbar.append(mark, status);

    /* Who is editing, when we know.

       Only for somebody who signed in with the service — a site using its own
       accounts has never told us a name, and inventing one would be worse
       than saying nothing. Dropped first on a narrow screen: it is a courtesy,
       and every other thing on this bar is a control. */
    const editor = window.liveEditEditor ?? null;

    if (editor?.greeting) {
        const hello = el('span', 'le-hello le-when-roomy', 'Welcome ' + editor.greeting);
        toolbar.append(hello);
    }

    let localeSelect = null;
    const locales = config.locales ?? {};
    if (Object.keys(locales).length > 1) {
        localeSelect = el('select', 'le-locale');
        localeSelect.title = 'Language you are editing';
        Object.entries(locales).forEach(([code, label]) => {
            const option = el('option', null, label);
            option.value = code;
            option.selected = code === (config.locale ?? 'en');
            localeSelect.append(option);
        });
        localeSelect.addEventListener('change', () => {
            window.location.search = '?locale=' + localeSelect.value;
        });
        toolbar.append(localeSelect);
    }

    const toggleButton = el('button', 'le-bar-btn', 'Edit site');
    toggleButton.type = 'button';

    // One glyph each, so they read at a glance and take no width from the
    // things that need words.
    const arrow = (flip) => '<svg width="15" height="15" viewBox="0 0 24 24" fill="none" aria-hidden="true"'
        + (flip ? ' style="transform: scaleX(-1)"' : '')
        + '><path d="M9 14 4 9l5-5" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"/>'
        + '<path d="M4 9h7a6 6 0 0 1 0 12H8" stroke="currentColor" stroke-width="1.8" stroke-linecap="round"/></svg>';

    const undoButton = el('button', 'le-round');
    undoButton.type = 'button';
    undoButton.title = 'Undo the last change you have not published';
    undoButton.setAttribute('aria-label', 'Undo');
    undoButton.innerHTML = arrow(false);

    const redoButton = el('button', 'le-round');
    redoButton.type = 'button';
    redoButton.title = 'Put back what you just undid';
    redoButton.setAttribute('aria-label', 'Redo');
    redoButton.innerHTML = arrow(true);

    // Filled in once the page has been read for its own navigation, and left
    // out entirely on a site with only one page.
    const pageSwitcher = el('div', 'le-pages');
    pageSwitcher.hidden = true;
    pageSwitcher.setAttribute('role', 'group');
    pageSwitcher.setAttribute('aria-label', 'Pages');

    /*
     * Which language is being edited.
     *
     * A select rather than a menu of our own: the list is short, it is a
     * choice from a fixed set, and a native control is the one thing on this
     * bar that already works with a keyboard, a screen reader and a phone
     * without us building any of it three times.
     *
     * Hidden on the sites that have one language, which is most of them. A
     * control offering a choice of one is furniture.
     */
    const languagePicker = el('select', 'le-lang');
    languagePicker.hidden = true;
    languagePicker.title = 'Which language you are editing';
    languagePicker.setAttribute('aria-label', 'Language');

    const changesButton = el('button', 'le-bar-btn le-when-roomy', 'Changes');
    changesButton.type = 'button';
    changesButton.title = 'Everything you have changed and not published';

    const previewButton = el('button', 'le-bar-btn le-when-roomy', 'Preview');
    previewButton.type = 'button';
    previewButton.title = 'See the page the way a visitor will';
    previewButton.hidden = true;

    /* Publishing: the one accent on the view, carrying how much is waiting.
       "Publish" alone does not say whether there is anything to publish, and
       a button that does nothing when pressed is how somebody stops trusting
       the rest of them. */
    const publishButton = el('button', 'le-publish');
    publishButton.type = 'button';
    publishButton.title = 'Put your changes live';
    publishButton.hidden = true;
    const publishLabel = el('span', null, 'Publish');
    const publishCount = el('span', 'le-publish-count');
    publishCount.hidden = true;
    publishButton.append(publishLabel, publishCount);

    toolbar.append(
        el('span', 'le-sep'),
        toggleButton,
        undoButton,
        redoButton,
        el("span", "le-sep"),
        pageSwitcher,
        languagePicker,
        changesButton,
        previewButton,
        publishButton,
    );

    (config.links ?? []).forEach((link) => {
        const anchor = el('a', 'le-btn-ghost', link.label);
        anchor.href = link.href;
        if (link.title) anchor.title = link.title;
        toolbar.append(anchor);
    });

    if (config.logout?.href) {
        if ((config.logout.method ?? 'get').toLowerCase() === 'post') {
            const form = document.createElement('form');
            form.method = 'POST';
            form.action = config.logout.href;
            const token = document.createElement('input');
            token.type = 'hidden';
            token.name = '_token';
            token.value = document.body.dataset.csrf ?? '';
            const submit = el('button', 'le-btn-ghost', 'Log out');
            submit.type = 'submit';
            form.append(token, submit);
            toolbar.append(form);
        } else {
            const anchor = el('a', 'le-btn-ghost', 'Log out');
            anchor.href = config.logout.href;
            toolbar.append(anchor);
        }
    }

    // ---- drawer ------------------------------------------------------------
    const drawer = el('div', 'le-drawer');
    drawer.setAttribute('role', 'dialog');
    drawer.setAttribute('aria-modal', 'true');
    drawer.setAttribute('aria-label', 'Edit content');

    const head = el('div', 'le-drawer-head');

    /* Edit · Changes · History.
       Changes and History are where somebody goes when they are unsure —
       "did that save", "what have I changed", "what went out last week" — so
       they are one click from the thing being edited rather than somewhere
       else entirely. */
    const tabs = el('div', 'le-tabs');
    tabs.setAttribute('role', 'tablist');

    const drawerTabs = {};
    ['Edit', 'Changes', 'History'].forEach((name) => {
        const tab = el('button', 'le-tab', name);
        tab.type = 'button';
        tab.dataset.tab = name;
        tab.setAttribute('role', 'tab');
        if (name === 'Edit') tab.classList.add('is-on');
        drawerTabs[name] = tab;
        tabs.append(tab);
    });

    const closeButton = el('button', 'le-close', '×');
    closeButton.type = 'button';
    closeButton.setAttribute('aria-label', 'Close');
    head.append(tabs, closeButton);

    // What is being edited, below the tabs.
    const subject = el('div', 'le-subject');
    const drawerTrail = el('div', 'le-trail');
    const drawerTitle = el('div', 'le-title', 'Text');
    subject.append(el('div', 'le-eyebrow', 'Selected'), drawerTrail, drawerTitle);

    const drawerFields = el('div', 'le-fields');

    const foot = el('div', 'le-foot');
    const drawerDelete = el('button', 'le-btn-danger le-start le-hidden', 'Delete');
    drawerDelete.type = 'button';
    const cancelButton = el('button', 'le-btn-outline', 'Cancel');
    cancelButton.type = 'button';
    const saveButton = el('button', 'le-btn', 'Save changes');
    saveButton.type = 'button';
    foot.append(drawerDelete, cancelButton, saveButton);

    drawer.append(head, subject, drawerFields, foot);

    // ---- floating link handle ---------------------------------------------
    const linkHandle = el('button', 'le-handle');
    linkHandle.type = 'button';
    linkHandle.setAttribute('aria-label', 'Edit this link');
    linkHandle.innerHTML = '&#9998;';

    // Backgrounds painted by the theme's stylesheet have nothing in the markup
    // to click, so they get their own hover handle.
    const bgHandle = el('button', 'le-handle le-handle-bg');
    bgHandle.type = 'button';
    bgHandle.setAttribute('aria-label', 'Replace this background image');
    bgHandle.title = 'Replace background image';
    bgHandle.textContent = 'Replace background';

    const hoverBox = el('div', 'le-hover');
    const hoverLabel = el('span', 'le-hover-label');
    hoverBox.append(hoverLabel);

    shadow.append(toolbar, drawer, linkHandle, bgHandle, hoverBox);

    // "Saved" can go by in a second; "this didn't take effect" is a sentence
    // somebody has to finish reading before it disappears.
    const toast = (message, hold = 1800) => {
        const node = el('div', 'le-toast', message);
        shadow.append(node);
        setTimeout(() => (node.style.opacity = '0'), hold);
        setTimeout(() => node.remove(), hold + 600);
    };

    /**
     * A dialog over the page.
     *
     * One of these rather than three hand-built ones, because the things that
     * are easy to forget are the same every time and all of them are the
     * difference between a dialog and a trap: Escape closes it, clicking the
     * darkened page behind closes it, focus moves into it so a keyboard can
     * reach the buttons, and it goes away cleanly.
     *
     * `dismissable: false` is for a dialog with work in flight — a translation
     * running, a publish in progress. Closing those halfway is how somebody
     * ends up paying for something they never received.
     */
    const modal = ({ title, subtitle, size = '', dismissable = true } = {}) => {
        const scrim = el('div', 'le-scrim');
        const card = el('div', `le-modal ${size}`.trim());
        card.setAttribute('role', 'dialog');
        card.setAttribute('aria-modal', 'true');

        const heading = el('div', 'le-modal-heading');
        const titleEl = el('div', 'le-modal-title', title ?? '');
        const subEl = el('div', 'le-modal-sub', subtitle ?? '');
        subEl.hidden = !subtitle;
        heading.append(titleEl, subEl);
        card.setAttribute('aria-label', title ?? 'Dialog');

        const close = el('button', 'le-close', '×');
        close.type = 'button';
        close.setAttribute('aria-label', 'Close');

        const head = el('div', 'le-modal-head');
        head.append(heading, close);

        const tabs = el('div', 'le-modal-tabs');
        tabs.hidden = true;
        const body = el('div', 'le-modal-body');
        const foot = el('div', 'le-modal-foot');
        foot.hidden = true;

        card.append(head, tabs, body, foot);
        scrim.append(card);

        // Where the keyboard was before this opened, so it can be put back.
        // Otherwise closing a dialog drops focus onto the document and the
        // next Tab starts again from the top of somebody else's website.
        const previous = document.activeElement;
        let shut = false;

        const dismiss = () => {
            if (shut) return;
            shut = true;
            document.removeEventListener('keydown', onKey, true);
            scrim.remove();
            previous?.focus?.();
            state.dismissable = true;
        };

        const onKey = (event) => {
            if (event.key === 'Escape' && state.dismissable) {
                event.stopPropagation();
                dismiss();
            }
        };

        const state = { dismissable };

        close.addEventListener('click', dismiss);
        scrim.addEventListener('mousedown', (event) => {
            if (event.target === scrim && state.dismissable) dismiss();
        });
        document.addEventListener('keydown', onKey, true);

        shadow.append(scrim);
        close.focus();

        return {
            card,
            body,
            foot,
            tabs,
            close: dismiss,
            title: (text) => (titleEl.textContent = text),
            subtitle: (text) => {
                subEl.textContent = text ?? '';
                subEl.hidden = !text;
            },
            // Turned off while something is in flight, back on when it lands.
            allowDismiss: (allowed) => {
                state.dismissable = allowed;
                close.hidden = !allowed;
            },
        };
    };

    return {
        root,
        shadow,
        toolbar,
        toggleButton,
        undoButton,
        redoButton,
        pageSwitcher,
        languagePicker,
        statusText,
        dot,
        localeSelect,
        drawer,
        drawerFoot: foot,
        drawerTabs,
        drawerSubject: subject,
        drawerTitle,
        drawerTrail,
        drawerFields,
        drawerDelete,
        publishButton,
        publishLabel,
        publishCount,
        previewButton,
        changesButton,
        closeButton,
        cancelButton,
        saveButton,
        linkHandle,
        bgHandle,
        hoverBox,
        hoverLabel,
        toast,
        modal,
    };
}
